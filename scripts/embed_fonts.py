#!/usr/bin/env python3
"""Generate a C++ source with the bundled fonts embedded as byte arrays."""

from __future__ import annotations

import pathlib
import sys

FONTS = {
    "kSansRegular": "LiberationSans-Regular.ttf",
    "kSansBold": "LiberationSans-Bold.ttf",
    "kSansItalic": "LiberationSans-Italic.ttf",
    "kSansBoldItalic": "LiberationSans-BoldItalic.ttf",
    "kMonoRegular": "LiberationMono-Regular.ttf",
}


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: embed_fonts.py <output-dir> <assets-fonts-dir>",
              file=sys.stderr)
        return 2

    out_dir = pathlib.Path(sys.argv[1])
    assets_dir = pathlib.Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    header = [
        "// Generated by scripts/embed_fonts.py. Do not edit.",
        "#pragma once",
        "",
        "namespace ab {",
        "namespace embedded_fonts {",
        "",
    ]
    source = [
        "// Generated by scripts/embed_fonts.py. Do not edit.",
        '#include "BundledFonts.h"',
        "",
        "namespace ab {",
        "namespace embedded_fonts {",
        "",
    ]

    for symbol, filename in FONTS.items():
        data = (assets_dir / filename).read_bytes()
        header.append(f"extern const unsigned char {symbol}[];")
        header.append(f"extern const unsigned int {symbol}Size;")
        source.append(f"extern const unsigned char {symbol}[] = {{")
        for offset in range(0, len(data), 12):
            chunk = data[offset:offset + 12]
            values = ", ".join(f"0x{byte:02x}" for byte in chunk)
            source.append(f"    {values},")
        source.append("};")
        source.append(
            f"extern const unsigned int {symbol}Size = sizeof({symbol});")
        source.append("")

    license_path = assets_dir / "LICENSE-Liberation.txt"
    if license_path.exists():
        license_text = license_path.read_text(encoding="utf-8")
        delimiter = "AB_FONT_LICENSE"
        while delimiter in license_text:
            delimiter += "_"
        header.append("extern const char kLicense[];")
        source.append(
            f'extern const char kLicense[] = R"{delimiter}('
            f"{license_text}){delimiter}\";")
        source.append("")

    header.extend(["}", "}", ""])
    source.extend(["}", "}", ""])

    (out_dir / "BundledFonts.h").write_text("\n".join(header),
                                            encoding="utf-8")
    (out_dir / "BundledFonts.cpp").write_text("\n".join(source),
                                              encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
